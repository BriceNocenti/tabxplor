say <- function(...) cat(..., "\n", sep = "", file = con)

# every footer line of one table (weight + Model: + interactions + colour legend + stars), which is
# what an export actually prints -- not the colour legend alone.
footer <- function(x, lang, theme)
  render_footer(tab_footer_streams(x, style = "prose", lang = lang, theme = theme),
                medium = "plain", theme = theme)

# one CASE = one table, shown across languages and (only where they differ) across palettes.
case <- function(title, call, themes = c("light", "print_minimalistic", "print_emphasis", "print_marks")) {
  say("\n")
  say("### ", title)
  say("")
  x <- tryCatch(suppressMessages(suppressWarnings(force(call))),
                error = function(e) { say("!! ", conditionMessage(e)); NULL })
  if (is.null(x)) return(invisible())
  for (th in themes) {
    for (lg in LANGS) {
      ln <- tryCatch(footer(x, lg, th), error = function(e) paste("!!", conditionMessage(e)))
      if (!length(ln)) next
      say("\n- ", th, " / ", lg)
      for (l in ln) say("  ", l)
    }
  }
  invisible()
}

