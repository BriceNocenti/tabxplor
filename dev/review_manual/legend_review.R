#   - IT WRITES MARKDOWN, and the maintainer annotates it in place: a regeneration must not undo the
#     structure they read it in. The annotations live in the git diff, so keep the layout stable.
# Usage:  OMP_NUM_THREADS=1 Rscript dev/review_manual/legend_review.R
#         -> dev/review_manual/legend_review.md

